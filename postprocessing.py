def parse_burst(data_dict,toff):
    N = data_dict["N"]
    fc = data_dict["fc"]
    startupbits = data_dict["startupbits"]
    os = data_dict["os"]
    numbits = data_dict["numbits"]
    numcycles = data_dict["numcycles"]
    y = data_dict["y"]
    t = data_dict["t"]
    repeatlength = data_dict["repeatlength"]
    #numpts = int(np.ceil((20+2*20+0.25)*os))
    #y_chirp_k = np.zeros([numpts,int(repeatlength)])
    y_chirp_k = np.zeros([int(os*numcycles),int(repeatlength)])
    #y_data_k = np.zeros([numpts,int(repeatlength)])
    y_data_k = np.zeros([int(N*os*(2*startupbits+numbits)),int(repeatlength)])
    # parse chirp
    if data_dict["channel_sound_enable"]:
        print("... channel sounding detected")
        Tsig = 1/fc*(numcycles)
        #Tsig = 1/fc*numpts/os
        #Tsig = N/fc*(numbits + 2* startupbits)
        tstart = toff
        tstop = tstart+Tsig
        #t_ = np.linspace(0,Tsig,numpts);
        t_ = np.linspace(0,Tsig,os*numcycles);
        y1 = np.array(y)
        t1 = np.array(t)
        print("... parsing channel sounding")
        for i in range(repeatlength):
            b = (t1>tstart) & (t1<tstop)
            t1_ = t1[b]-tstart
            y_k = np.interp(t_,t1_,y1[b])
            if i==0:
                y_ = y_k+0
            else:
                y_ = y_+y_k
            y_chirp_k[:,i] = y_k*1
            tstart = tstart+Tsig
            tstop = tstop+Tsig
        data_dict["t_chirp"] = t_
        data_dict["y_chirp"] = y_/repeatlength
        data_dict["y_chirp_k"] = y_chirp_k
    else:
        tstart = toff
        data_dict["t_chirp"] = y_chirp_k[:,0]
        data_dict["y_chirp"] = y_chirp_k[:,0]
        data_dict["y_chirp_k"] = y_chirp_k
    # parse data
    #Tsig = 1/fc*numpts/os
    #Tsig = N/fc*(2*startupbits+numbits)
    Tsig = N/fc*(numbits + 2* startupbits)
    tstop = tstart+Tsig
    #t_ = np.linspace(0,Tsig,numpts);
    #t_ = np.linspace(0,Tsig,os*numcycles);
    t_ = np.linspace(0,Tsig,N*os*(2*startupbits+numbits));
    y1 = np.array(y)
    t1 = np.array(t)
    print("... parsing data signal")
    for i in range(repeatlength):
        b = (t1>=tstart) & (t1<=tstop)
        t1_ = t1[b]-tstart
        y_k = np.interp(t_,t1_,y1[b])
        if i==0:
            y_ = y_k+0
        else:
            y_ = y_+y_k
        y_data_k[:,i] = y_k*1
        tstart = tstart+Tsig
        tstop = tstop+Tsig
        data_dict["t_data"] = t_
        data_dict["y_data"] = y_/repeatlength
        data_dict["y_data_k"] = y_data_k
    return data_dict

