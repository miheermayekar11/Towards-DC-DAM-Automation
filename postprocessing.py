def make_fft(t,y):
    dt = t[1]-t[0]
    L = len(t)
    samplerate = 1/dt
    f = np.fft.fftfreq(L, d=1./samplerate)
    Y = np.fft.fft(y)
    return f, Y

def interp_fft(f_,f,y):
    ry_ = np.interp(f_,np.fft.fftshift(f),np.fft.fftshift(np.real(y)))
    iy_ = np.interp(f_,np.fft.fftshift(f),np.fft.fftshift(np.imag(y)))
    return ry_ + 1j*iy_

